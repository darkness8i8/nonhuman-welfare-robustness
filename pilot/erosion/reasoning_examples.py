"""Write reasoning_examples.md: fully rendered reasoning-recipe training examples per family, with the supervised
(loss) tokens marked, to check by eye that (1) history turns carry no reasoning, (2) only the final assistant turn
is supervised, (3) the mask starts right after `<|im_start|>assistant\\n` and ends with the end-of-turn token.
Renders through reasoning_sft.Renderer, the code train_unsloth.py --reasoning uses.
Usage: reasoning_examples.py <nemotron_jsonl> <out_md>   (rows from build_nemotron.py; tokenizers from the Hub)"""
import json, os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from transformers import AutoTokenizer
from reasoning_sft import TEMPLATES, Renderer, read_template, turn_prefixes

TOKENIZER = {"qwen": "Qwen/Qwen3-8B-Base", "olmo": "allenai/Olmo-3-1025-7B"}
OPEN, CLOSE = "[[LOSS>>", "<<LOSS]]"


def marked(tok, ids, labels):
    """Decode, wrapping each supervised run of tokens in OPEN ... CLOSE."""
    out, i = [], 0
    while i < len(ids):
        j, sup = i, labels[i] != -100
        while j < len(ids) and (labels[j] != -100) == sup:
            j += 1
        text = tok.decode(ids[i:j])
        out.append(f"{OPEN}{text}{CLOSE}" if sup else text)
        i = j
    return "".join(out)


src, out = sys.argv[1:3]
rows = [json.loads(l) for l in open(src, encoding="utf-8")]
# a short row with 3+ assistant turns: shows the history rule (turn 1 vs the last turn) and fits on a page
row = min((r for r in rows if sum(m["role"] == "assistant" for m in r["messages"]) >= 3),
          key=lambda r: len(json.dumps(r)))
lines = ["# Reasoning recipe: rendered training examples", "",
         "Generated by `pilot/erosion/reasoning_examples.py` from the build_nemotron.py output, through the same code as",
         "`train_unsloth.py --reasoning` (`pilot/reasoning_sft.py`). Supervised tokens are wrapped in "
         f"`{OPEN}` ... `{CLOSE}`; everything else is context (label -100).", "",
         "Each Nemotron row becomes one example per assistant turn. Below, for one row (Nemotron uuid "
         f"`{row['group']}`, {sum(m['role'] == 'assistant' for m in row['messages'])} assistant turns), the FIRST and the "
         "LAST turn's examples per family. In the last one, the earlier assistant turns appear with their calls but "
         "without reasoning, exactly as vLLM renders the history at inference with the same template.", ""]
for fam in ("qwen", "olmo"):
    tok = AutoTokenizer.from_pretrained(TOKENIZER[fam])
    rd = Renderer(tok, read_template(TEMPLATES[fam]))
    pre = turn_prefixes(row["messages"])
    for name, pm in (("first assistant turn", pre[0]), (f"last assistant turn ({len(pre)} of {len(pre)})", pre[-1])):
        ids, labels = rd.example(pm, row["tools"])
        lines += [f"## {fam}: {name} ({len(ids)} tokens, {sum(l != -100 for l in labels)} supervised)", "",
                  "````text", marked(tok, ids, labels), "````", ""]
    ids, labels = rd.example([{"role": "user", "content": "Write a document."},
                              {"role": "assistant", "content": "(replay document text)"}], None)
    lines += [f"## {fam}: chat replay row (empty reasoning block, supervised like a tool turn)", "",
              "````text", marked(tok, ids, labels), "````", ""]
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", out)
